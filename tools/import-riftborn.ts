// Pulls the heroes (stats, skills and pictures) out of the Riftborn repo into this game.
// Usage (from this repo's root, with Riftborn cloned next to it or anywhere):
//   npx esbuild tools/import-riftborn.ts --bundle --platform=node --outfile=/tmp/import.js \
//     --alias:riftborn=../Game- && node /tmp/import.js
// Writes data/heroes.js and assets/heroes/<id>.png.

import { writeFileSync, mkdirSync } from "node:fs";
import { HEROES } from "riftborn/shared/game";
import { HERO_ART_DATA } from "riftborn/client/src/heroArt.data";

const skill = (s: any) => s && !s.kind?.includes("passive") ? { name: s.name, kind: s.kind, damage: s.damage ?? 0, desc: s.desc ?? "" } : null;

mkdirSync("assets/heroes", { recursive: true });
const out: any[] = [];
for (const [id, h] of Object.entries(HEROES) as [string, any][]) {
  const png = HERO_ART_DATA[id]?.south;
  if (h.summon || h.formOf || !png) continue;
  writeFileSync(`assets/heroes/${id}.png`, Buffer.from(png.split(",")[1]!, "base64"));
  out.push({
    id,
    name: h.name,
    role: h.role,
    stars: h.stars,
    hp: h.maxHp,
    damage: h.damage,
    speed: h.speed,
    attack: h.attack,
    skills: [skill(h.skill), skill(h.skill2)].filter(Boolean),
  });
}
writeFileSync(
  "data/heroes.js",
  "// Generated by tools/import-riftborn.ts from the Riftborn repo. Do not edit by hand.\nwindow.RIFTBORN_HEROES = " + JSON.stringify(out, null, 1) + ";\n",
);
console.log(`imported ${out.length} heroes`);
